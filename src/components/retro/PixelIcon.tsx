export type PixelIconName = keyof typeof glyphs;

type Props = {
  name: PixelIconName;
  /** rendered width in px; height follows the glyph's aspect */
  size?: number;
  className?: string;
  title?: string;
};

export default function PixelIcon({ name, size = 16, className = "", title }: Props) {
  const rows = glyphs[name];
  const w = rows[0].length;
  const h = rows.length;
  const rects: JSX.Element[] = [];

  rows.forEach((row, y) => {
    let x = 0;
    while (x < w) {
      const ch = row[x];
      if (ch === ".") {
        x++;
        continue;
      }
      let end = x;
      while (end + 1 < w && row[end + 1] === ch) end++;
      rects.push(
        <rect
          key={`${x}-${y}`}
          x={x}
          y={y}
          width={end - x + 1}
          height={1}
          opacity={ch === "+" ? 0.35 : 1}
        />,
      );
      x = end + 1;
    }
  });

  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      width={size}
      height={(size * h) / w}
      fill="currentColor"
      shapeRendering="crispEdges"
      className={`inline-block shrink-0 ${className}`}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {rects}
    </svg>
  );
}
